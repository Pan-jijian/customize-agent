/**
 * 4.61 部位分池的**并列构件限定语**（对象作用域最大缺口）。
 *
 * ## 缺陷
 *
 * `LOCATION_WORD_SOURCE` 同时含「基础」与「垫层」，而 `qualifyLocationHit` 原先只组合
 * **实体**限定词（项目部/办公/标段），构件类别限定语被丢弃 → `locationGroupForMatch` 取
 * 窗口内**最后一个**部位词 → 「基础垫层」与「地坪垫层」并成同一池「垫层」。
 *
 * 实机后果（巢湖）：正文「基础垫层C20」与「基础垫层C15」被报成「垫层 C20/C15/C25 三套口径」——
 * **真实矛盾被埋在一堆假同池值里**：既定位不准（报的是裸词垫层），也无法修复
 *（修复需要唯一权威值，而按裸词取的权威是别的部位的值）。
 *
 * ## 判据
 *
 * 部位词**紧邻**另一个部位词时构成更具体的部位（基础垫层 / 地坪地面 / 屋面找平）；
 * 容器/范围词（主体/结构/工程/项目）不作限定——「主体结构外墙」仍归「外墙」，保留既有意图。
 *
 * ## 测试纪律
 *
 * 本文件全部用例都在**真实句子**上（取自 `assets/巢湖施工组织设计-doc-*` 实机正文），
 * 且已逐条验证「关掉新判据即失败」。
 */
import { describe, expect, it } from 'vitest';
import { locationGroupForMatch } from '@/services/document-workflow/integrity/detectors/detectors';

const groupOf = (text: string, token: string) => locationGroupForMatch(text, text.indexOf(token), token, 0);

describe('4.61 并列构件限定语参与部位分池', () => {
  it('实机形态：「基础垫层」自成一体，不与裸词「垫层」混池', () => {
    expect(groupOf('为单层配套建筑，框架结构，混凝土强度等级以C30、C35为主，基础垫层C20', 'C20')).toBe('基础垫层');
    expect(groupOf('基础混凝土采用C30商品混凝土，垫层C15，钢筋HRB400按图绑扎', 'C15')).toBe('垫层');
  });

  it('同对象的真矛盾**仍进同一池**（分池不放松真冲突）', () => {
    expect(groupOf('基础垫层C20，独立基础C35', 'C20')).toBe('基础垫层');
    expect(groupOf('基础垫层C15混凝土，独立基础C35混凝土', 'C15')).toBe('基础垫层');
  });

  // **不变式守卫**（非新行为用例）：本条在加入新判据前后**都通过**，它守的是「新判据不破坏原意图」。
  // 已在代码注释中说明为何容器词必须排除——否则「主体结构外墙」会被并成新池，反而制造假分离。
  it('容器/范围词不作限定：「主体结构外墙」仍归「外墙」（保留既有意图）', () => {
    expect(groupOf('主体结构外墙采用A5.0砌块', 'A5.0')).toBe('外墙');
    expect(groupOf('外墙采用A3.5砌块', 'A3.5')).toBe('外墙');
  });

  it('其它构件限定语同族：地坪/屋面/道路与部位词紧邻时构成复合部位', () => {
    expect(groupOf('地坪地面采用C25混凝土', 'C25')).toBe('地坪地面');
    expect(groupOf('屋面找平层采用M10砂浆', 'M10')).toBe('屋面找平');
  });
});
