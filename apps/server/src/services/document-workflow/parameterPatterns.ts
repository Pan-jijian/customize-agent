/**
 * 量化参数/精确值识别正则的统一口径（唯一权威来源）。
 * 各文件禁止再内联定义 mm/cm/m³/MPa 类单位正则：
 * - 数值+单位、标准编号、尺寸乘式的提取统一走 PRECISE_TOKEN_RE；
 * - 事实行是否量化走 QUANTIFIED_FACT_RE；
 * - 事实值是否含数值/单位/型号走 HAS_QUANTIFIED_VALUE_RE；
 * - 证据行是否含量化参数走 EVIDENCE_PARAMETER_RE；
 * - 工艺参数（kN/坡度/压实度等）与设备规格走本文件 PROCESS_PARAMETER_RE / DEVICE_SPEC_RE。
 */

/** 精确参数/编号提取：数值+单位、尺寸乘式、标准规范编号（GB/JGJ/ISO 等）。
 * 尺寸乘式分支带前置负向后顾 (?<![\d.])：科学记数法「1.0×10⁻²」的「0×10」与小数尺寸「6.5x10」的「5x10」
 * 曾被误提取为独立 token（真实文档审计暴露）；整数尺寸（500x300 / 300x300x10）不受影响。
 * r28m M24d D1（面积盲区根治）：单位组重排——m2/m3/m³/m²/㎡/平方米 多字符/变体必须在 m 前
 *（「1436.4m²」曾被 m 分支截断为「1436.4m」）；尾部边界断言由 \b 改为 (?![\w\u00B2\u00B3])——\b 对 ㎡/%/℃ 等
 * 非词形单位后接标点时边界不成立而漏提（「937.72㎡；」）；上标²³兜底防「m²」截断。 */
export const PRECISE_TOKEN_RE = /(?:\b[A-Z]{1,8}[\w./-]*\d[\w./-]*\b|\b\d+(?:\.\d+)?\s*(?:mm|cm|m2|m3|m³|m²|㎡|平方米|m|km|kg|g|t|L|ml|MPa|kPa|℃|%|台|套|个|项|批|次|份|人|小时|分钟|日历天|天|周|月|年|万元|元)(?![\w\u00B2\u00B3])|(?<![\d.])\b\d+\s*[×xX]\s*\d+(?:\s*[×xX]\s*\d+)?\b|\b(?:GB|GB\/T|ISO|IEC|IEEE|RFC|API|DB\d*|T\/[A-Z]+)\s*[\w.-]+\b)/giu;

/** 事实行量化判断：数值+单位、管径/直径 DN/φ/Φ、标准编号 GB/JGJ */
export const QUANTIFIED_FACT_RE = /\d+(?:\.\d+)?\s*(?:mm|cm|m|km|㎡|m²|m3|m³|kg|g|t|L|ml|MPa|kPa|℃|%|台|套|个|项|批|次|份|人|小时|分钟|日历天|天|周|月|年)|DN\s*\d+|φ\s*\d+|Φ\s*\d+|GB\s*\d+|JGJ\s*\d+/iu;

/** 事实值是否含数值/单位/型号（事实值筛选与参数事实判定共用同一口径） */
export const HAS_QUANTIFIED_VALUE_RE = /\d|DN|φ|Φ|mm|cm|m²|m3|m³|MPa|kPa|℃|%|GB|JGJ|ISO|IEC|台|套|个|项|批|次|份|人|㎡|日历天|万元|元|型号|规格|数量|单位/iu;

/** 证据行是否含可量化参数：数值+单位、管径、混凝土/钢筋牌号、标准编号、尺寸乘式 */
export const EVIDENCE_PARAMETER_RE = /\d+(?:\.\d+)?\s*(?:mm|cm|m|km|㎡|m²|m3|m³|kg|g|t|L|ml|MPa|kPa|℃|%|台|套|个|项|批|次|份|人|小时|分钟|日历天|天|周|月|年)|DN\s*\d+|Φ\s*\d+|φ\s*\d+|C\d{2,}|HRB\d+|GB\/?T?\s*[\w.-]+|JGJ\s*[\w.-]+|\d+\s*[×xX]\s*\d+/iu;

/** 工艺参数（强度等级/尺寸/时间/绝缘电阻/坡度/压实度/试验类等）：分部分项施工方案小节的参数密度校验与专业评分共用口径。
 * 多字符单位（m³/m²/㎡/m/s）必须先于单字符 m 参与交替，避免贪婪截断误配。
 * r28 扩围（r27b 归因）：绿化/苗木类工艺参数形态（地径D10、养护期为二年、成活率≥95%
 * 等）并入同一权威口径——绿化工程无 mm/MPa 级参数不等于无工艺参数。 */
export const PROCESS_PARAMETER_RE = /\d+(?:\.\d+)?\s*(?:m³|m3|m²|㎡|mm|cm|m\/s|m|km|MPa|kN|kN\/m²|kPa|℃|%|d|h|min|MΩ|t|次\/天)|[MC]\d{1,3}(?:\.\d+)?|[<>≤≥]\s*\d+(?:\.\d+)?\s*(?:mm|MPa|%|d)|间距[≤<]?\s*\d+|偏差[≤<]?\s*\d+|坡度\s*\d+(?:\.\d+)?(?::\d+|%)|压实度\s*[≥>]?\s*\d+|坍落度|闭水试验|静载试验|拉拔试验|拉拔检测|探伤|试验压力|锚固长度|搭接长度|保护层厚度|养护时间|饱满度|垂直度|平整度|含水率|(?:地径|胸径|苗高|蓬径|冠丛高|株高|株距|行距|种植深度|覆土厚度|土球直径)\s*[≥≤<>=]?\s*[DΦφd]?\s*\d+(?:\.\d+)?|(?:养护期|养护周期)\s*(?:为|不少于|不低于)?\s*[一二三四五六七八九十两\d]+(?:个)?(?:月|年)|(?:成活率|保存率|苗木覆盖率)\s*[≥≤<>=]?\s*\d+(?:\.\d+)?\s*%|(?:防护挑网|安全网|防护网|围挡|警戒(?:区|线|距离)|防护栏杆).{0,12}(?:宽度|高度|距离|范围)[^，。；;]{0,8}\d+(?:\.\d+)?\s*m|(?:宽度|高度|距离|范围)[^，。；;]{0,8}\d+(?:\.\d+)?\s*m.{0,12}(?:防护挑网|安全网|防护网|围挡|警戒|防护栏杆)/giu;

// 设备配置参数（配电箱/控制箱型号、容量、IP 等级等）：设备清单型小节以型号规格为参数载体
export const DEVICE_SPEC_RE = /\d[A-Z][A-Z0-9a-z]*\b|[A-Z]{1,2}\d{2,3}\b|\d+(?:\.\d+)?\s*(?:kW|kVA|KVA|KW)\b|IP\d{2}/gu;

/** 正文量化参数（专业评分"事实落位率"与参数密度检查共用口径）：数值+常用单位 */
export const QUANTIFIED_BODY_PARAM_RE = /\d+(?:\.\d+)?\s*(?:m²|㎡|m3|m³|mm|cm|m|km|kg|t|MPa|kPa|℃|%|日历天|天|层|台|套|个|项|次|份|人|小时)/giu;

/** 规格粘连值段的单位集（与 PRECISE_TOKEN_RE 单位组同口径；含归一化形态——判定在
 * normalizeEngineeringTextForFactMatch 之后进行，平方米→m2、日历天→天、小时→h、吨→t）。
 * 粘连判定只问「此处是否存在一个完整数值段」，故单位集与主提取器同源即可，不另立口径。 */
const GLUED_VALUE_UNIT = 'mm|cm|m2|m3|m³|m²|㎡|平方米|m|km|kg|g|t|吨|l|ml|mpa|kpa|kn|kw|kv|℃|%|台|套|个|项|批|次|份|人|h|d|min|天|周|月|年|万元|元';

/** 粘连值段（数量段）形态：带小数（1.941 / 25.851，可带单位）或带单位（5m），且整数段无多余
 * 前导零（0.5 合法、000 非法）。两要件缺一不可：
 * - 「小数或单位必居其一」——否则纯代号（HRB400 可切出 4|00）会被误判粘连；
 * - 「整数段无多余前导零」——否则 Φ1000mm 会被切成 1|000mm 误判粘连（1000 是真实量值）。 */
const GLUED_VALUE_SEGMENT = `(?:[1-9]\\d*\\.\\d+(?:${GLUED_VALUE_UNIT})?|(?:[1-9]\\d*|0\\.\\d+)\\s*(?:${GLUED_VALUE_UNIT}))`;

/** 规格粘连（字母/直径符号起头的代号段 + 数量段无分隔粘连）单源判定：代号段以数字收尾、其后
 * 紧跟完整数量段，两段之间无任何分隔符——
 *   HRB400+1.941t → HRB4001.941t；HRB400+25.851t → HRB40025.851t；DN40+5m → DN405m。
 * 该 token 的数值核（4001.941 / 40025.851 / 405）**不是正文中存在的任何一个数**，是提取器
 * 按型号分支贪婪吞并数量段产生的拼接产物：据其报缺口即假缺口、据其进修复轮即误删正确正文。
 * 判定为「存在性」——只要 token 内存在一个合法的「代号|数量段」边界即成立（无需定准切分点：
 * 代号位长是行业惯例而非项目数据，写死切分反成新的知识表）。 */
export const SPEC_GLUED_VALUE_RE = new RegExp(`^[A-Za-zΦφΔ][\\w./-]*\\d${GLUED_VALUE_SEGMENT}$`, 'iu');

/** 规格粘连（代号在 token 之外：提取器自数字起匹配）：token 自身为「数字段 + 完整数量段」——
 * Φ25+1.941t 的 token 是 251.941t（Φ 不入 ASCII 型号分支），拼接核 251.941 非正文任何数。
 * 单用本式会误伤普通量值（424.2m 亦可切出 4|24.2m），故必须与语境代号同判（见
 * isSpecGluedValueToken）。 */
export const SPEC_GLUED_DIGITS_RE = new RegExp(`^\\d+${GLUED_VALUE_SEGMENT}$`, 'u');

/** 直径/管径/钢筋牌号代号（语境侧，紧邻 token 前）：与 SPEC_GLUED_DIGITS_RE 合判，
 * 命中即「代号 + 数量」粘连（Φ251.941t 的 251.941t）。 */
export const SPEC_GLUE_MARK_RE = /(?:DN|De|HRB|HPB|Φ|φ)/iu;
