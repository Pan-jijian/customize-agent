/** 评审问题 → 定向修复指令（保持与 blockerFixInstructionFor 同风格：局部 patch、不新增小节、不丢事实） */
export function qingtianFixInstructionFor(issues: QingtianReviewIssue[]): string {
  const first = issues[0];
  const header = QINGTIAN_FIX_HEADER_BY_DIMENSION[first?.dimension || ''] || '【全维度评审定向修复】';
  const body = QINGTIAN_FIX_BODY_BY_DIMENSION[first?.dimension || ''] || '该章节正文存在全维度评审检出的质量问题。请以局部 patch 方式结合缺陷描述逐项修复：精确定位问题句，删除错误内容或按专业规范改写，保持其余内容与事实数据不变。';
  const issueList = issues.map((issue, index) => `问题 ${index + 1}：\n- 位置：${issue.location}\n- 原文片段：${issue.quote}\n- 风险等级：${issue.riskLevel}\n- 对标依据：${issue.basis}\n- 问题描述：${issue.description}`).join('\n\n');
  return [header, body, '只修复下列问题，其余内容保持原样：', issueList].join('\n');
}
